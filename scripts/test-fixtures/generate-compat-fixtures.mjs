#!/usr/bin/env node

import { mkdir, readFile, writeFile, cp } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const outputDir = path.resolve(process.argv[2] || path.join("test-results", "compat-fixtures"));
await mkdir(outputDir, { recursive: true });

// These fixtures are deliberately deterministic and provider-free. They are
// enough to exercise preview registration, file-type routing, and the real
// editor/session contracts without spending Credits.
const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=", "base64");
const gif = Buffer.from("R0lGODlhAQABAIAAAAAAAP///ywAAAAAAQABAAACAUwAOw==", "base64");
await writeFile(path.join(outputDir, "reference.png"), png);
await writeFile(path.join(outputDir, "single-frame.gif"), gif);
await cp(path.resolve("internal", "pptxeditor", "assets", "blank.pptx"), path.join(outputDir, "blank.pptx"));

const manifest = {
  schema: "officedex.compatibility-fixture.v1",
  generatedBy: "scripts/test-fixtures/generate-compat-fixtures.mjs",
  files: [
    { name: "blank.pptx", documentType: "pptx", purpose: "PPTX preview/editor/timeline smoke" },
    { name: "reference.png", documentType: "img", purpose: "image region-stage smoke" },
    { name: "single-frame.gif", documentType: "gif", purpose: "GIF frame-zero boundary smoke" },
  ],
  unsupported: {
    multiFrameGif: "Requires a provider-free multi-frame fixture from the image pipeline; run hosted GIF E2E when enabled.",
    xlsx: "Generated by the real host because the workbook fixture must match the installed sheet converter.",
  },
};
await writeFile(path.join(outputDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

if (process.argv.includes("--verify")) {
  const pptx = await readFile(path.join(outputDir, "blank.pptx"));
  if (pptx[0] !== 0x50 || pptx[1] !== 0x4b) throw new Error("blank.pptx is not a ZIP/PPTX fixture");
  if ((await readFile(path.join(outputDir, "reference.png"))).length === 0) throw new Error("reference.png is empty");
  if ((await readFile(path.join(outputDir, "single-frame.gif"))).toString("ascii", 0, 6) !== "GIF89a") throw new Error("single-frame.gif is invalid");
  const loaded = JSON.parse(await readFile(path.join(outputDir, "manifest.json"), "utf8"));
  if (loaded.schema !== "officedex.compatibility-fixture.v1" || loaded.files.length !== 3) throw new Error("fixture manifest is invalid");
}

console.log(outputDir);
